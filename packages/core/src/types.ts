/**
 * 判定の最小単位。原文の断片ひとつと、それを打ち切る打鍵列の集合を持つ。
 *
 * 文脈依存（「っ」の子音重ね、「ん」の n / nn など）は単位を組み立てる側で解決し、
 * 実行時の判定は単位内の前方一致だけで完結させる。
 */
export interface Unit {
  /** この単位に対応する原文の断片。全単位を連結すると原文に戻る。 */
  readonly source: string;
  /**
   * 受理される打鍵列。キーボードが打てるもの、つまり印字可能な ASCII で綴る。
   * 空でない要素が少なくともひとつ必要。
   *
   * `[0]` は推奨経路として扱われ、ガイド表示（{@link Session.remaining}）に使われる。
   * 判定は最短一致で確定するため、ある候補が別の候補の接頭辞になってはいけない。
   */
  readonly candidates: readonly string[];
}

/** 1打鍵の判定結果。 */
export type InputResult =
  /** 受理された。 */
  | "hit"
  /** 受理されなかった。セッションの状態は変化しない。 */
  | "miss"
  /** 受理され、かつ原文を打ち切った。 */
  | "complete";

/**
 * 入力方式。原文を打鍵単位列へ変換する。
 *
 * 打鍵は ASCII なので、原文をどう綴るか（ローマ字をどう解釈するかなど）は
 * 判定の外側にあたるこの層の仕事になる。綴れない文字を持つ原文は、
 * 打鍵列にできないという形でセッションを作る時点ではじかれる。
 */
export type Scheme = (source: string) => readonly Unit[];
